-- ============================================================
--  Ahnstoppable Learning: baseline schema
-- ============================================================
-- Brings ANY database to the schema as of 2026-11-09:
--   * an empty database gets every table, constraint and index;
--   * a database built by the old runner (backend/migrations-legacy, 001–011,
--     e.g. production) only gets what it is missing. No rows are deleted.
--
-- Every statement is idempotent, so running this file twice is harmless
-- (CI checks that). There is no BEGIN/COMMIT: the Supabase CLI and
-- backend/scripts/migrate.js both run the whole file as one transaction.
--
-- Do not edit this file to change the schema. Add a new migration instead
-- (see supabase/README.md).

-- The backfills in section 2 turn timestamps into class days with ::date, the
-- same way the old runner's connections did (APP_TIMEZONE).
SET TIME ZONE 'America/Los_Angeles';


-- ── 1. Tables (final shape, in dependency order) ────────────────────────────

-- Users (students AND professors share the same table; role distinguishes them)
CREATE TABLE IF NOT EXISTS users (
    id          SERIAL PRIMARY KEY,
    email       TEXT UNIQUE,            -- professors only; roster students have none
    password    TEXT,                   -- bcrypt hash; NULL until a roster student creates one
    name        TEXT NOT NULL,          -- "First Last"
    sort_name   TEXT,                   -- "Last, First" for the sign-in dropdown
    role        TEXT NOT NULL DEFAULT 'student'  -- 'student' | 'professor'
                CHECK (role IN ('student','professor')),
    talents     INTEGER NOT NULL DEFAULT 0,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Classes
CREATE TABLE IF NOT EXISTS classes (
    id          SERIAL PRIMARY KEY,
    title       TEXT NOT NULL,          -- e.g. "ADV 375"
    section     TEXT,                   -- e.g. "Section 01"
    start_time  TIME,
    end_time    TIME,
    join_code   TEXT NOT NULL UNIQUE,   -- professor shares this 6-char code
    professor_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Class memberships (students enrolled in classes)
CREATE TABLE IF NOT EXISTS class_members (
    user_id     INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    class_id    INTEGER NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
    joined_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (user_id, class_id)
);

-- Discussion posts (created by professors)
CREATE TABLE IF NOT EXISTS posts (
    id          SERIAL PRIMARY KEY,
    class_id    INTEGER NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
    author_id   INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title       TEXT NOT NULL,
    content     TEXT NOT NULL,
    post_date   DATE NOT NULL DEFAULT CURRENT_DATE,  -- used for day-by-day view
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Comments on posts (students or professor)
CREATE TABLE IF NOT EXISTS comments (
    id          SERIAL PRIMARY KEY,
    post_id     INTEGER NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
    author_id   INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    content     TEXT NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    edited_at   TIMESTAMPTZ                             -- set when the author edits it
);

-- Replies to comments
CREATE TABLE IF NOT EXISTS replies (
    id          SERIAL PRIMARY KEY,
    comment_id  INTEGER NOT NULL REFERENCES comments(id) ON DELETE CASCADE,
    author_id   INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    content     TEXT NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    edited_at   TIMESTAMPTZ                             -- set when the author edits it
);

-- Standing student questions (asked any time, independent of posts)
CREATE TABLE IF NOT EXISTS questions (
    id          SERIAL PRIMARY KEY,
    class_id    INTEGER NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
    author_id   INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    content     TEXT NOT NULL,
    answer      TEXT,                                   -- professor's written answer
    answered_at TIMESTAMPTZ,
    asked_date  DATE NOT NULL DEFAULT CURRENT_DATE,     -- day-by-day view, like posts.post_date
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    edited_at        TIMESTAMPTZ,                       -- the asker edited the question
    answer_edited_at TIMESTAMPTZ                        -- the professor edited the answer
);

-- Understanding-check rounds (professor starts / ends one during class, or
-- prepares one ahead of time for a given day)
CREATE TABLE IF NOT EXISTS understand_rounds (
    id            SERIAL PRIMARY KEY,
    class_id      INTEGER NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
    label         TEXT,                                 -- e.g. "Slide 12: regression"
    scheduled_for DATE NOT NULL DEFAULT CURRENT_DATE,   -- the class day it belongs to
    started_at    TIMESTAMPTZ DEFAULT NOW(),            -- NULL = prepared, not started yet
    ended_at      TIMESTAMPTZ                           -- NULL while the round is open
);

-- Student responses (👍 👋 👎), one per student per round, upserted on change
CREATE TABLE IF NOT EXISTS understand_checks (
    id          SERIAL PRIMARY KEY,
    round_id    INTEGER NOT NULL REFERENCES understand_rounds(id) ON DELETE CASCADE,
    class_id    INTEGER NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
    user_id     INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    response    TEXT NOT NULL CHECK (response IN ('thumbs_up','hand','thumbs_down')),
    checked_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (round_id, user_id)
);

-- Polls (professor asks a question with 2–6 text options; one open per class;
-- can be prepared ahead of time for a given day)
CREATE TABLE IF NOT EXISTS polls (
    id            SERIAL PRIMARY KEY,
    class_id      INTEGER NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
    question      TEXT NOT NULL,
    scheduled_for DATE NOT NULL DEFAULT CURRENT_DATE,   -- the class day it belongs to
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    opened_at     TIMESTAMPTZ,                          -- NULL = prepared, not started yet
    closed_at     TIMESTAMPTZ                           -- NULL while the poll is open
);

CREATE TABLE IF NOT EXISTS poll_options (
    id          SERIAL PRIMARY KEY,
    poll_id     INTEGER NOT NULL REFERENCES polls(id) ON DELETE CASCADE,
    text        TEXT NOT NULL,
    position    SMALLINT NOT NULL,                      -- 1-based display order
    UNIQUE (poll_id, position),
    UNIQUE (poll_id, id)                                -- target for the composite FK below
);

-- Poll votes, one per student per poll, upserted on change
CREATE TABLE IF NOT EXISTS poll_votes (
    id          SERIAL PRIMARY KEY,
    poll_id     INTEGER NOT NULL REFERENCES polls(id) ON DELETE CASCADE,
    option_id   INTEGER NOT NULL REFERENCES poll_options(id) ON DELETE CASCADE,
    class_id    INTEGER NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
    user_id     INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    voted_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (poll_id, user_id),
    -- the chosen option must belong to the same poll
    FOREIGN KEY (poll_id, option_id) REFERENCES poll_options(poll_id, id) ON DELETE CASCADE
);

-- AI summaries of a class day's student questions (professor only, on demand)
CREATE TABLE IF NOT EXISTS question_summaries (
    id             SERIAL PRIMARY KEY,
    class_id       INTEGER NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
    summary_date   DATE NOT NULL,
    summary        JSONB NOT NULL,                      -- structured result (overview, themes, …)
    question_count INTEGER NOT NULL,                    -- how many questions it covered
    model          TEXT NOT NULL,                       -- model that produced it
    created_by     INTEGER REFERENCES users(id) ON DELETE SET NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (class_id, summary_date)
);

-- Follow-up replies under an answered question (students and the professor)
CREATE TABLE IF NOT EXISTS question_replies (
    id          SERIAL PRIMARY KEY,
    question_id INTEGER NOT NULL REFERENCES questions(id) ON DELETE CASCADE,
    author_id   INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    content     TEXT NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    edited_at   TIMESTAMPTZ
);

-- Likes on discussion comments and replies (one per person; only counts are shown)
CREATE TABLE IF NOT EXISTS comment_likes (
    comment_id INTEGER NOT NULL REFERENCES comments(id) ON DELETE CASCADE,
    user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (comment_id, user_id)
);
CREATE TABLE IF NOT EXISTS reply_likes (
    reply_id   INTEGER NOT NULL REFERENCES replies(id) ON DELETE CASCADE,
    user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (reply_id, user_id)
);

-- Thumbs-up on questions, answers and replies in the Questions card
CREATE TABLE IF NOT EXISTS question_likes (
    question_id INTEGER NOT NULL REFERENCES questions(id) ON DELETE CASCADE,
    user_id     INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (question_id, user_id)
);
CREATE TABLE IF NOT EXISTS answer_likes (
    question_id INTEGER NOT NULL REFERENCES questions(id) ON DELETE CASCADE,
    user_id     INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (question_id, user_id)
);
CREATE TABLE IF NOT EXISTS question_reply_likes (
    reply_id   INTEGER NOT NULL REFERENCES question_replies(id) ON DELETE CASCADE,
    user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (reply_id, user_id)
);

-- Per-class settings for the student study assistant (off until the professor turns it on)
CREATE TABLE IF NOT EXISTS class_ai_settings (
    class_id     INTEGER PRIMARY KEY REFERENCES classes(id) ON DELETE CASCADE,
    enabled      BOOLEAN NOT NULL DEFAULT false,
    instructions TEXT    NOT NULL DEFAULT '',          -- professor's rules for the assistant, ≤ 2,000 chars
    course_notes TEXT    NOT NULL DEFAULT '',          -- key concepts, syllabus points, ≤ 20,000 chars
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Study-assistant chats: one private thread per student per class. Deleted
-- after ASSISTANT_RETENTION_DAYS (default 120) by services/retention.js.
CREATE TABLE IF NOT EXISTS assistant_messages (
    id            SERIAL PRIMARY KEY,
    class_id      INTEGER NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
    user_id       INTEGER NOT NULL REFERENCES users(id)   ON DELETE CASCADE,
    role          TEXT    NOT NULL CHECK (role IN ('user','model')),
    content       TEXT    NOT NULL,
    model         TEXT,                                -- which Gemini model answered (model rows)
    input_tokens  INTEGER,
    output_tokens INTEGER,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Anonymous AI summaries of what students asked the study assistant on a day
-- (professor only), shaped like question_summaries
CREATE TABLE IF NOT EXISTS assistant_summaries (
    id             SERIAL PRIMARY KEY,
    class_id       INTEGER NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
    summary_date   DATE NOT NULL,
    summary        JSONB NOT NULL,                      -- structured result (overview, themes, …)
    question_count INTEGER NOT NULL,                    -- how many messages it covered
    model          TEXT NOT NULL,                       -- model that produced it
    created_by     INTEGER REFERENCES users(id) ON DELETE SET NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (class_id, summary_date)
);


-- ── 2. Catch-up for databases built by the old runner ───────────────────────
-- On an empty database everything below is a no-op. On an older database each
-- step finishes what the matching legacy migration did.

-- 001: understanding checks belong to a round. The legacy migration deleted
-- every pre-round answer to get there; this file never deletes data, so stop
-- with a clear message instead (no database in use should hit this).
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'understand_checks' AND column_name = 'round_id'
  ) THEN
    RAISE EXCEPTION 'understand_checks has no round_id column. This database predates legacy migration 001, '
      'which deleted all understanding-check answers. Migrate it by hand; the baseline will not delete data.';
  END IF;
END $$;

ALTER TABLE understand_checks DROP CONSTRAINT IF EXISTS understand_checks_class_id_user_id_key;
-- One answer per student per round. Fresh databases get this from the CREATE
-- TABLE above; the legacy runner named it understand_checks_round_user_key.
-- Only add it if no unique constraint on (round_id, user_id) exists yet.
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint c
    WHERE c.conrelid = 'public.understand_checks'::regclass
      AND c.contype = 'u'
      AND c.conkey::int2[] = ARRAY[
        (SELECT attnum FROM pg_attribute WHERE attrelid = c.conrelid AND attname = 'round_id'),
        (SELECT attnum FROM pg_attribute WHERE attrelid = c.conrelid AND attname = 'user_id')
      ]::int2[]
  ) THEN
    ALTER TABLE understand_checks ADD CONSTRAINT understand_checks_round_user_key UNIQUE (round_id, user_id);
  END IF;
EXCEPTION WHEN duplicate_table OR duplicate_object THEN NULL;
END $$;

-- 004: roster students have no email and may not have a password yet.
ALTER TABLE users ALTER COLUMN email DROP NOT NULL;
ALTER TABLE users ALTER COLUMN password DROP NOT NULL;
ALTER TABLE users ADD COLUMN IF NOT EXISTS sort_name TEXT;

-- 005: polls and understanding checks belong to a day and can be prepared.
ALTER TABLE polls ADD COLUMN IF NOT EXISTS scheduled_for DATE;
ALTER TABLE polls ADD COLUMN IF NOT EXISTS opened_at TIMESTAMPTZ;
UPDATE polls SET opened_at = created_at WHERE opened_at IS NULL AND scheduled_for IS NULL;
UPDATE polls SET scheduled_for = created_at::date WHERE scheduled_for IS NULL;
ALTER TABLE polls ALTER COLUMN scheduled_for SET DEFAULT CURRENT_DATE;
ALTER TABLE polls ALTER COLUMN scheduled_for SET NOT NULL;

ALTER TABLE understand_rounds ADD COLUMN IF NOT EXISTS scheduled_for DATE;
UPDATE understand_rounds SET scheduled_for = started_at::date WHERE scheduled_for IS NULL;
ALTER TABLE understand_rounds ALTER COLUMN scheduled_for SET DEFAULT CURRENT_DATE;
ALTER TABLE understand_rounds ALTER COLUMN scheduled_for SET NOT NULL;
ALTER TABLE understand_rounds ALTER COLUMN started_at DROP NOT NULL;

-- Only a started, unclosed poll / check counts as "open". Recreated so older
-- databases (where any unclosed one counted) get the current condition.
DROP INDEX IF EXISTS idx_polls_one_open_per_class;
CREATE UNIQUE INDEX idx_polls_one_open_per_class
    ON polls(class_id) WHERE opened_at IS NOT NULL AND closed_at IS NULL;
DROP INDEX IF EXISTS idx_rounds_one_open_per_class;
CREATE UNIQUE INDEX idx_rounds_one_open_per_class
    ON understand_rounds(class_id) WHERE started_at IS NOT NULL AND ended_at IS NULL;

-- 008 / 010: remember when comments, replies, questions and answers were edited.
ALTER TABLE comments         ADD COLUMN IF NOT EXISTS edited_at        TIMESTAMPTZ;
ALTER TABLE replies          ADD COLUMN IF NOT EXISTS edited_at        TIMESTAMPTZ;
ALTER TABLE questions        ADD COLUMN IF NOT EXISTS edited_at        TIMESTAMPTZ;
ALTER TABLE questions        ADD COLUMN IF NOT EXISTS answer_edited_at TIMESTAMPTZ;
ALTER TABLE question_replies ADD COLUMN IF NOT EXISTS edited_at        TIMESTAMPTZ;


